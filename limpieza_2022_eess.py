"""## 9. Outliers (se marcan, no se eliminan)"""

# Buscamos datos anomalos en los precios con el metodo del IQR.
# Cada producto tiene un precio distinto (GNC vs gasoil) y los precios suben durante el año,
# por eso calculamos Q1, Q3 e IQR dentro de cada producto y mes.
# Usamos 3 * IQR en vez de 1.5 * IQR: con 1.5 se marcaba cerca del 6% de las filas en cada columna,
# y muchas son diferencias reales entre provincias (ejemplo: Tierra del Fuego es mas barata).
for col in ['precio_sin_impuestos', 'precio_con_impuestos', 'precio_surtidor']:
    Q1 = df.groupby(['producto', 'periodo'])[col].transform(lambda s: s.quantile(0.25))
    Q3 = df.groupby(['producto', 'periodo'])[col].transform(lambda s: s.quantile(0.75))
    IQR = Q3 - Q1
    limite_inferior = Q1 - 3 * IQR
    limite_superior = Q3 + 3 * IQR
    df['outlier_' + col] = (df[col] < limite_inferior) | (df[col] > limite_superior)
    print(col, '-> outliers:', df['outlier_' + col].sum())

# Como ejemplo, vemos los limites (con 3 * IQR) de precio_surtidor para nafta super en enero
ejemplo = df[(df['producto'] == 'Nafta (súper) entre 92 y 95 Ron') & (df['periodo'] == '2022-01-01')]['precio_surtidor']
