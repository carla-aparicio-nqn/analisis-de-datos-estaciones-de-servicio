# Buscamos datos anomalos en el volumen. Varia mucho (de 0.01 a millones), asi que usamos su logaritmo
# y calculamos el IQR dentro de cada producto y canal. Usamos 3 * IQR (en vez de 1.5) para marcar solo los valores muy extremos.
log_vol = np.log10(df['volumen_ajustado'])
