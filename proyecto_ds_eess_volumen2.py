"""**Interpretación (ejecución de referencia, semilla 42; los números pueden variar levemente con otras versiones de las librerías).** Con k = 5 K-means separa:
- **Cluster GNC** (~8 % de las filas): casi todo GNC, volumen mediano ≈ 81.000 (frente a ≈ 45–50 de los demás) y precio bajo (≈ 49). Es la estructura dominante y refleja la diferencia de escala del volumen por producto.
- **Cluster de registros exentos** (~3 %): reúne todas las filas con `exentos = 1`.
- **Cluster de precios altos** (~8 %): precios entre ≈ 230 y 1.999 (mediana ≈ 822) frente a ≈ 100 del resto. No está documentado a qué corresponde (otra unidad de precio, otro concepto de reporte, etc.); conviene revisarlo con la fuente.
- **Dos clusters de combustibles líquidos** (~30 % y ~50 %) que se diferencian sobre todo por el **tipo de negocio**: bocas duales (líquidos + GNC) frente a bocas de solo líquidos.

El silhouette más alto aparece en k = 2 (≈ 0,66), que solo separa GNC del resto: una partición demasiado gruesa para describir el mercado. Por eso la regla del notebook exige k ≥ 3 y se toma el codo (k = 5). Es una segmentación válida y descriptiva, pero dos de los grupos (GNC y precios altos) provienen de escalas de `volumen` y de `precio` por producto/registro, no necesariamente de comportamientos comerciales distintos.

### 4.2 DBSCAN
**Idea:** un punto es *núcleo* si tiene al menos `min_samples` vecinos (él incluido) a distancia ≤ `eps`; los clusters son componentes conexas de puntos núcleo y los puntos sin vecindad suficiente son **ruido** (`-1`). No exige fijar el número de clusters y detecta formas arbitrarias y atípicos.

- **`eps`**: radio de vecindad. Muy pequeño → casi todo es ruido; muy grande → todo se fusiona en un solo cluster. Se guía con el gráfico de **k-distancias** (distancia al k-ésimo vecino ordenada): el "codo" sugiere el valor.
- **`min_samples`**: densidad mínima. Regla práctica: ≥ dimensión + 1, comúnmente $2d$ en datos de $d$ dimensiones.

Como DBSCAN usa una sola densidad global, rinde mal si los grupos tienen densidades muy distintas, y esa es una limitación relevante aquí (productos con escalas de volumen muy diferentes).
"""

# Celda 13 · DBSCAN: gráfico de k-distancias y análisis de sensibilidad
d_dim = Z.shape[1]
MS0 = max(2 * d_dim, 10)
t0 = time.time()
nn = NearestNeighbors(n_neighbors=MS0).fit(Z)
kdist = np.sort(nn.kneighbors(Z)[0][:, -1])
print(f'k-distancias calculadas en {time.time()-t0:.1f}s (min_samples base = {MS0})')

# codo de la curva de k-distancias (distancia máxima a la cuerda, ejes normalizados)
xs = np.linspace(0, 1, len(kdist)); ys = (kdist - kdist.min()) / (kdist.max() - kdist.min() + 1e-12)
EPS0 = float(kdist[int(np.argmax(np.abs(ys - xs)))])
print(f'eps sugerido por el codo: {EPS0:.3f} | percentiles de k-distancia 50/90/95/99: '
      f'{np.percentile(kdist,[50,90,95,99]).round(3)}')

plt.figure(figsize=(8, 4.5)); plt.plot(kdist); plt.axhline(EPS0, color='r', ls='--', label=f'eps≈{EPS0:.2f}')
plt.title(f'Gráfico de k-distancias (k={MS0})'); plt.xlabel('puntos ordenados'); plt.ylabel('distancia al k-ésimo vecino'); plt.legend(); plt.show()

# Sensibilidad en una muestra (DBSCAN es costoso en memoria cuando hay muchos puntos casi idénticos)
N_MUESTRA = 15000
im = np.random.RandomState(SEMILLA).choice(len(Z), N_MUESTRA, replace=False)
Zm = Z[im]
res = []
for f_eps in [0.5, 1.0, 1.5]:
    for f_ms in [0.5, 1, 2]:
        eps, ms = EPS0 * f_eps, int(MS0 * f_ms)
        lab = DBSCAN(eps=eps, min_samples=ms).fit_predict(Zm)
        mask = lab != -1; ncl = len(set(lab[mask]))
        sil = np.nan
        if ncl >= 2:
            ii = np.random.RandomState(SEMILLA).choice(np.where(mask)[0], min(5000, mask.sum()), replace=False)
            sil = silhouette_score(Zm[ii], lab[ii])
        res.append(dict(eps=eps, min_samples=ms, clusters=ncl, ruido_pct=(~mask).mean() * 100,
                        mayor_cluster_pct=(np.bincount(lab[mask]).max() / len(lab) * 100) if ncl else 0, silhouette=sil))
sens = pd.DataFrame(res)
display(sens)

# Celda 14 · DBSCAN: configuración elegida, ajuste final, ruido y caracterización
# Regla: entre configuraciones con >=2 clusters y ruido <= 15 %, la de mayor silhouette;
# si ninguna cumple, la más cercana al eps sugerido por el codo.
cand = sens[(sens.clusters >= 2) & (sens.ruido_pct <= 15)].dropna(subset=['silhouette'])
if len(cand):
    mejor = cand.sort_values('silhouette', ascending=False).iloc[0]
else:
    mejor = sens.iloc[(sens.eps - EPS0).abs().argsort().iloc[0]]
EPS, MS = float(mejor['eps']), int(mejor['min_samples'])
print(f'Configuración elegida: eps={EPS:.3f}, min_samples={MS}')

db = DBSCAN(eps=EPS, min_samples=MS).fit(Z)
panel['cl_dbscan'] = db.labels_
n_cl_db = len(set(db.labels_)) - (1 if -1 in db.labels_ else 0)
print(f'Clusters: {n_cl_db} | ruido: {(db.labels_==-1).sum():,} ({(db.labels_==-1).mean():.1%})')

plt.figure(figsize=(8, 6))
lab_i = db.labels_[idx]
plt.scatter(Z[idx][lab_i == -1, 0], Z[idx][lab_i == -1, 1], s=6, c='lightgray', label='ruido')
sns.scatterplot(x=Z[idx][lab_i != -1, 0], y=Z[idx][lab_i != -1, 1], hue=lab_i[lab_i != -1], palette='tab10', s=8)
plt.title('DBSCAN en CP1–CP2 (gris = ruido)'); plt.xlabel('CP1'); plt.ylabel('CP2'); plt.show()

display(perfil_clusters('cl_dbscan').sort_values('n', ascending=False).head(15))
print('Composición por producto de los 15 grupos más grandes y del ruido (-1):')
top = panel['cl_dbscan'].value_counts().head(15).index.union([-1])
display(pd.crosstab(panel['cl_dbscan'], panel['producto'], normalize='index').loc[top] * 100)
pureza = (pd.crosstab(panel['cl_dbscan'], panel['producto'], normalize='index').drop(index=-1, errors='ignore').max(axis=1))
