display(panel[panel.cl_dbscan == -1].nlargest(8, 'volumen')[['periodo', 'producto', 'canal_de_comercializacion', 'volumen', 'precio_con_impuestos']])

"""### 4.3 Comparación de algoritmos
Para que la comparación sea justa, las métricas internas (silhouette, Davies-Bouldin, Calinski-Harabasz) se calculan **solo sobre los puntos que DBSCAN no marcó como ruido**, y se calculan para K-means sobre ese mismo subconjunto. Estas métricas favorecen clusters compactos y convexos, por lo que **penalizan a DBSCAN por construcción**; se interpretan junto con la geometría de los datos y no como veredicto único.
"""

# Celda 15 · Comparación K-means vs DBSCAN
mask = panel['cl_dbscan'].values != -1
