"""**Ventajas y limitaciones**

| | K-means | DBSCAN |
|---|---|---|
| Fortalezas | Rápido, asigna todas las observaciones, centroides interpretables, métricas internas bien definidas | No requiere fijar *k*, encuentra formas arbitrarias, aísla atípicos como ruido |
| Debilidades | Asume grupos esféricos y de tamaño parecido; los atípicos arrastran los centroides; hay que elegir *k* | Una sola densidad global; muy sensible a `eps`; en datos mixtos con dummies, muchos puntos casi idénticos generan un cluster gigante |
| Geometría de estos datos | Las dummies de producto/canal/tipo de negocio crean grupos compactos y bien separados, y `y`/`log_precio` forman nubes continuas dentro de cada uno → K-means los captura con pocos grupos | Con una densidad global, DBSCAN rodea cada combinación densa y la separa: produce **decenas de clusters pequeños casi puros en un producto** en lugar de segmentos de mercado |

**Decisión.** Para **segmentar el mercado** es más apropiado **K-means**: los datos son mixtos (categorías + magnitudes), la estructura dominante son pocos grupos compactos asociados al producto, al tipo de negocio y al nivel de precio, y se necesita asignar todas las observaciones. En la ejecución de referencia DBSCAN (eps ≈ 0,35, `min_samples` = 7) devolvió **110 clusters** casi puros en un producto (ARI ≈ 0,22 frente a K-means), con ≈ 1,9 % de ruido; su silhouette es menor y su índice de Calinski-Harabasz mucho menor que el de K-means, aunque su Davies-Bouldin es algo mejor. Esa fragmentación es demasiado fina para interpretar. Donde **sí** aporta DBSCAN es como **detector de observaciones raras**: su ruido contiene los volúmenes extremos (GNC de más de 800.000, gasoil de hasta ≈ 680.000 en canales Agro, Transporte de cargas y Otros sectores), candidatos a revisar por posibles errores de carga o de unidad. Se recomienda usar K-means para segmentar y DBSCAN para auditar atípicos.

## 5. Representaciones vectoriales, similitud y base de datos vectorial

**¿Hay variables textuales?** Sí, pero son **texto corto y categórico** (operador, bandera, tipo de negocio, localidad, provincia, producto, canal), no texto libre. Por eso un embedding de lenguaje aporta una similitud *semántica y ortográfica* entre nombres (p. ej. "Estación de Servicio" ≈ "Est. de Servicios", marcas y localidades parecidas), pero **no captura el comportamiento de ventas**: dos estaciones con texto parecido pueden vender volúmenes muy distintos. Por eso las variables numéricas (`y_medio`, `n_obs`) se guardan como **metadatos** y no dentro del embedding.

**Construcción de la representación.**
- *Preferida:* `sentence-transformers` (`paraphrase-multilingual-MiniLM-L12-v2`), un Transformer que convierte cada texto en un vector denso de 384 dimensiones.
- *Alternativa sin descargas:* TF-IDF de n-gramas de caracteres + SVD (LSA), un embedding clásico y determinista. La celda cae en esta opción si el modelo no puede descargarse.

Los vectores se normalizan (norma 1). **Similitud coseno:** $\cos(a,b)=\frac{a\cdot b}{\|a\|\|b\|}$; **distancia coseno** $=1-\cos(a,b)$. Con vectores unitarios el coseno es el producto punto.
"""

# Celda 16 · Documentos de texto (una fila por combinación única) y embeddings
panel['texto'] = (panel['operador'].str.title() + ' | bandera ' + panel['bandera'].str.title() + ' | ' +
                  panel['tipo_negocio'] + ' | ' + panel['localidad'].str.title() + ', ' + panel['provincia'].str.title() +
                  ' | ' + panel['producto'] + ' | canal ' + panel['canal_de_comercializacion'])

docs = (panel.groupby('texto')
             .agg(n_obs=('y', 'size'), y_medio=('y', 'mean'), provincia=('provincia', 'first'),
                  producto=('producto', 'first'), bandera=('bandera', 'first'), canal=('canal_de_comercializacion', 'first'))
             .reset_index())
docs['id'] = ['doc_' + str(i) for i in range(len(docs))]
print('Documentos únicos:', len(docs))
print('Ejemplo:', docs['texto'].iloc[0])

def construir_embedder(textos):
    if USAR_SENTENCE_TRANSFORMERS:
        try:
            from sentence_transformers import SentenceTransformer
            modelo = SentenceTransformer('paraphrase-multilingual-MiniLM-L12-v2')
            fn = lambda t: modelo.encode(list(t), batch_size=128, normalize_embeddings=True, show_progress_bar=False)
            return 'sentence-transformers (MiniLM multilingüe)', fn
        except Exception as e:
            print('sentence-transformers no disponible, se usa TF-IDF + SVD. Motivo:', repr(e)[:120])
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.decomposition import TruncatedSVD
    from sklearn.preprocessing import Normalizer
    tfidf = TfidfVectorizer(analyzer='char_wb', ngram_range=(3, 5), min_df=2, sublinear_tf=True)
    svd = TruncatedSVD(n_components=128, random_state=SEMILLA)
    norm = Normalizer()
    svd.fit(tfidf.fit_transform(textos))
    fn = lambda t: norm.transform(svd.transform(tfidf.transform(list(t))))
    return 'TF-IDF (n-gramas de caracteres) + SVD', fn

nombre_emb, embed = construir_embedder(docs['texto'].tolist())
t0 = time.time()
E = np.asarray(embed(docs['texto'].tolist()), dtype='float32')
print(f'Embeddings: {nombre_emb} | forma {E.shape} | {time.time()-t0:.1f}s | norma media {np.linalg.norm(E, axis=1).mean():.3f}')

# Celda 17 · Similitud coseno y observaciones similares
def similares(i, k=6):
    sim = E @ E[i]                                  # vectores unitarios: producto punto = coseno
    orden = np.argsort(-sim)[1:k + 1]
    out = docs.iloc[orden][['texto', 'producto', 'provincia', 'y_medio']].copy()
    out['similitud_coseno'] = sim[orden]; out['distancia_coseno'] = 1 - sim[orden]
    return out

cand = docs[(docs.bandera == 'YPF') & (docs.producto == 'GNC') & (docs.provincia == 'BUENOS AIRES')]
ref = int(cand.index[0]) if len(cand) else 0
print('Referencia:', docs.loc[ref, 'texto'])
display(similares(ref))

# verificación contra la implementación de scikit-learn
sk = cosine_similarity(E[ref:ref + 1], E)[0]
assert np.allclose(sk, E @ E[ref], atol=1e-4), 'el producto punto no coincide con cosine_similarity'
print('OK: producto punto == cosine_similarity para vectores normalizados')

# Clustering sobre los embeddings (K-means esférico por vectores normalizados)
