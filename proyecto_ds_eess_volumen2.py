"""## 7. Soporte teórico de los errores

**Métricas de regresión** (con $n$ observaciones, $e_i=y_i-\hat y_i$):

| Métrica | Fórmula | Lectura |
|---|---|---|
| MAE | $\frac1n\sum\lvert e_i\rvert$ | Error medio en las unidades del objetivo; robusto a atípicos. |
| MSE | $\frac1n\sum e_i^2$ | Penaliza cuadráticamente los errores grandes; es la pérdida que se optimiza. |
| RMSE | $\sqrt{\text{MSE}}$ | Misma unidad que el objetivo; más sensible a atípicos que el MAE. RMSE ≫ MAE indica errores grandes aislados. |
| R² | $1-\frac{\sum e_i^2}{\sum (y_i-\bar y)^2}$ | Proporción de varianza explicada **respecto de predecir siempre la media**. Puede ser negativo en datos nuevos. |

**Error en escala logarítmica.** Un error $e$ en $\log(1+y)$ equivale a un error **relativo** de $\approx e^{e}-1$. Por eso el RMSE en escala log trata igual a un error del 50 % en una estación chica o grande, mientras que el RMSE original lo domina el volumen absoluto. La transformación inversa $\exp(\hat y)-1$ de un promedio en log estima la **mediana** condicional, no la media (se subestima la media si la distribución es asimétrica).

**Descomposición del error:** $\mathbb{E}[(y-\hat f)^2]=\text{sesgo}^2+\text{varianza}+\sigma^2_{\text{irreducible}}$.
- **Subajuste (alto sesgo):** error alto en train **y** en validación; el modelo es demasiado simple (p. ej. el perceptrón frente al MLP). Acción: más capacidad o mejores variables.
- **Sobreajuste (alta varianza):** error muy bajo en train y notablemente mayor en validación; la curva de validación sube mientras la de entrenamiento baja. Acciones: *early stopping*, Dropout, L2, menos parámetros, más datos.
- **Cambio de distribución (*drift*):** si el error de **prueba** supera al de validación sin señales de sobreajuste, el futuro difiere del pasado (precios nominales que cambian por inflación, otra composición de estaciones). Es el riesgo central de pronosticar con datos de pocos períodos.

**Fuga de información (*data leakage*).** Es un error de *diseño*, no de cálculo: métricas anormalmente buenas en validación y malas en producción. Fuentes típicas: ajustar el escalador/imputador con todos los datos, partir al azar series temporales, usar variables del mismo período que no se conocen al predecir, o usar clusters calculados con el objetivo.

**Línea base.** Un modelo solo aporta valor si supera a la **persistencia** ("el volumen será el del último período observado"), que es muy competitiva en series con memoria. Mejorar sobre la mediana por producto es una condición necesaria pero débil.

**Incertidumbre.** Con 8 períodos y cobertura desigual, las diferencias pequeñas entre modelos pueden no ser significativas; conviene repetir con varias semillas y, si hubiera más períodos, usar validación cruzada temporal (*rolling origin*).

| Síntoma | Diagnóstico probable | Qué hacer |
|---|---|---|
| Train ≪ val ≈ test | Sobreajuste | Regularizar, simplificar, parar antes |
| Train ≈ val ≈ test, todos altos | Subajuste o falta de señal | Más variables, más capacidad |
| val bajo, test alto | Drift temporal | Revisar variables nominales (precios), reentrenar con datos recientes |
| Resultado "demasiado bueno" | Posible fuga | Auditar variables y orden del *fit* del preprocesamiento |
| R² original negativo, R² log positivo | Unos pocos valores gigantes dominan | Reportar ambas escalas; revisar atípicos y unidades |
"""

